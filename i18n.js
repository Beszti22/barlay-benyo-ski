function applyI18n(lang) {
  const dict = I18N[lang] || I18N.hu;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-attr]").forEach(el => {
    el.getAttribute("data-i18n-attr").split("|").forEach(pair => {
      const [attr, key] = pair.split(":");
      if (dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  const titleKey = document.documentElement.getAttribute("data-i18n-page-title");
  if (titleKey && dict[titleKey]) document.title = dict[titleKey];
  localStorage.setItem("bb-lang", lang);
}

function initI18n() {
  const stored = localStorage.getItem("bb-lang");
  const lang = stored || (navigator.language.startsWith("en") ? "en" : "hu");
  applyI18n(lang);
  document.querySelectorAll("[data-lang-toggle]").forEach(btn => {
    btn.addEventListener("click", () => {
      const current = document.documentElement.lang === "en" ? "en" : "hu";
      applyI18n(current === "hu" ? "en" : "hu");
    });
  });
}

document.addEventListener("DOMContentLoaded", initI18n);
